/* ---- AI insight narratives (pu + so) ----
   The insights payloads are generated by an LLM (~5-10s per generation) on
   top of a full KPI sweep, so they are cached with a longer TTL than the
   operational caches. Narrative analytics may be up to 5 minutes stale — an
   accepted trade because regenerating on every view open re-billed several
   seconds to the contributor consoles. */
const INSIGHTS_TTL_MS = 300000
