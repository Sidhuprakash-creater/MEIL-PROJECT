/**
 * Helper utilities
 */
export function getAllSubsidiaries(): MeilSubsidiary[] {
  return MEIL_SUBSIDIARIES
}

export function getSubsidiaryByCode(code: string): MeilSubsidiary | undefined {
  return MEIL_SUBSIDIARIES.find(s => s.code === code || s.id === code)
}

export function getAllBusinessUnits(): MeilBusinessUnit[] {
  return MEIL_BUSINESS_UNITS
}

export function getBusinessUnitsBySubsidiary(subsidiaryCode: string): MeilBusinessUnit[] {
  return MEIL_BUSINESS_UNITS.filter(
    b => b.subsidiaryCode === subsidiaryCode || b.subsidiaryCode.toLowerCase() === subsidiaryCode.toLowerCase()
  )
}

export function getBusinessUnitById(id: string): MeilBusinessUnit | undefined {
  return MEIL_BUSINESS_UNITS.find(b => b.id === id || b.code === id)
}

export function getProjectsByBU(buId: string): MeilProject[] {
  const bu = getBusinessUnitById(buId)
  return bu ? bu.projects : []
}

export function getAllMeilProjects(): MeilProject[] {
  return MEIL_BUSINESS_UNITS.flatMap(b => b.projects)
}

export function getMeilProjectById(projectId: string): MeilProject | undefined {
  return getAllMeilProjects().find(p => p.id === projectId || p.code === projectId)
}
