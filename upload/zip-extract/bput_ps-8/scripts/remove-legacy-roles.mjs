/**
 * One-off cleanup: remove legacy reviewer / governance roles and their demo
 * users from the SQLite DB. Site operations roles & data are untouched.
 *
 * Roles removed: GROUP_ADMIN, SUPER_ADMIN (legacy), BU_REVIEWER,
 * SUBSIDIARY_REVIEWER, GROUP_REVIEWER, ESG_MANAGER, BRSR_MANAGER, AUDITOR,
 * EXECUTIVE.
 *
 * Usage: node scripts/remove-legacy-roles.mjs [--dry]
 */
import { PrismaClient } from '@prisma/client'

const db = new PrismaClient()
const dry = process.argv.includes('--dry')

const LEGACY_ROLES = [
  'GROUP_ADMIN', 'SUPER_ADMIN', 'BU_REVIEWER', 'SUBSIDIARY_REVIEWER',
  'GROUP_REVIEWER', 'ESG_MANAGER', 'BRSR_MANAGER', 'AUDITOR', 'EXECUTIVE',
]

async function main() {
  const roles = await db.role.findMany({
    where: { key: { in: LEGACY_ROLES } },
    select: { id: true, key: true },
  })
  const roleIds = roles.map(r => r.id)
  console.log('Legacy roles found in DB:', roles.map(r => r.key).join(', ') || '(none)')

  const users = await db.user.findMany({
    where: { userRoles: { some: { roleId: { in: roleIds } } } },
    select: { id: true, email: true, name: true },
  })
  const userIds = users.map(u => u.id)
  console.log('Users with legacy roles:', users.map(u => u.email).join(', ') || '(none)')
  if (users.length === 0 && roleIds.length === 0) { console.log('Nothing to clean.'); return }

  const keeper = await db.user.findUnique({ where: { email: 'rohit@meil-esg.in' }, select: { id: true, name: true } })
  if (!keeper) throw new Error('Keeper user rohit@meil-esg.in not found — aborting')

  for (const id of userIds) {
    let logs = 0, evidenceReassigned = 0, verifications = 0, reviewerCleared = 0, activities = 0
    if (!dry) {
      // audit logs have a required FK to the user; reassign/scrub dependents first
      const res = await Promise.all([
        db.auditLog.deleteMany({ where: { actorId: id } }),
        db.evidence.updateMany({ where: { uploaderId: id }, data: { uploaderId: keeper.id } }),
        db.evidence.updateMany({ where: { verifiedBy: id }, data: { verifiedBy: keeper.id } }),
        db.submission.updateMany({ where: { currentReviewerId: id }, data: { currentReviewerId: null } }),
        db.activity.deleteMany({ where: { actorId: id } }),
      ])
      ;[logs, evidenceReassigned, verifications, reviewerCleared, activities] = res.map(r => r.count)
      // notifications, userRoles, userScopes cascade on user delete
      await db.user.delete({ where: { id } })
    }
    console.log(`  user ${id}: auditLogs=${logs} evidenceReassigned=${evidenceReassigned} verifications=${verifications} reviewerCleared=${reviewerCleared} activities=${activities} deleted=${!dry}`)
  }

  // Re-point illustrative reports generated by removed users
  if (!dry) {
    const reports = await db.report.updateMany({ where: { generatedBy: { in: userIds } }, data: { generatedBy: keeper.id, generatedByName: keeper.name } })
    console.log(`reports re-pointed: ${reports.count}`)
  }

  for (const id of roleIds) {
    if (!dry) await db.role.delete({ where: { id } }) // rolePermissions cascade
  }
  if (!dry) console.log(`roles deleted: ${roleIds.length}`)

  const remainingUsers = await db.user.findMany({ select: { email: true } })
  const remainingRoles = await db.role.findMany({ select: { key: true } })
  console.log('Remaining users:', remainingUsers.map(u => u.email).sort().join(', '))
  console.log('Remaining roles:', remainingRoles.map(r => r.key).sort().join(', '))
  if (dry) console.log('DRY RUN — nothing was written.')
}

main()
  .catch((e) => { console.error(e); process.exit(1) })
  .finally(async () => { await db.$disconnect() })
